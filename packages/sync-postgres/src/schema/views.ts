/**
 * Live views.
 *
 * Every query against a mirror table has to remember `where "_deleted_at" is
 * null`, and forgetting it is the most common query mistake: a seat count that
 * includes users who left, a join that resurrects a revoked membership.
 * Fivetran and dbt users solve this with a view over each soft-deleted table.
 * Ours are generated from the catalog, in the same pass as the tables, so they
 * can never drift from them.
 *
 * Only the view layer is new. The engine keeps writing, redacting, reconciling
 * and reporting freshness against the base tables, and the base tables remain
 * the place to tell "deleted" from "never seen" (docs/consistency.md).
 */
import type { Logger, TableDef } from '@workos/sync-engine'
import type { SqlClient } from '../db/client.js'
import { quoteIdent, safeIdentifier } from './identifiers.js'

export const LIVE_VIEW_SUFFIX = '_live'

/**
 * How every generated view's comment begins, and so how the engine tells its
 * own views from one somebody else created under the same name.
 */
export const GENERATED_BY = 'Generated by @workos/sync-postgres'

/**
 * `<stream>_live`, truncated the same way table names are, so a long stream
 * name cannot produce a view name that Postgres silently cuts to something
 * else.
 */
export function liveViewName(stream: TableDef): string {
  return safeIdentifier(`${stream.name}${LIVE_VIEW_SUFFIX}`)
}

const CREATE_VIEW = 'create or replace view '

/**
 * DDL for one stream's live view: the `create or replace view` and its
 * `comment on view` as one string, because they are one unit. The comment is
 * how `applyViewStatement` recognises the engine's own views, so a view
 * without it would look like somebody else's to the next run; the two are
 * applied in a single transaction. Empty for append-only streams: they have
 * no `_deleted_at` column, so there is nothing to filter and a view would
 * only suggest there was.
 *
 * `select *` is deliberate: the view must expose every column the table has,
 * including ones promoted later through `extraColumns`. Postgres expands `*`
 * when the view is created, not when it is queried, which is why
 * `buildSchemaSql` emits these after `addColumnsSql` — re-creating the view
 * is how it picks up a new column.
 */
export function liveViewSql(stream: TableDef, schema: string): string[] {
  if (stream.mode === 'append') return []
  const { create, comment } = liveViewStatements(stream, schema)
  return [`${create};\n${comment};`]
}

/** The two statements behind a stream's live view, without their semicolons. */
function liveViewStatements(stream: TableDef, schema: string): { create: string; comment: string } {
  const s = quoteIdent(schema)
  const table = quoteIdent(safeIdentifier(stream.name))
  const view = quoteIdent(liveViewName(stream))
  const comment =
    `${GENERATED_BY}: ${schema}.${stream.name} without tombstoned rows ` +
    `("_deleted_at" is null). Do not edit; it is re-created every time the schema is applied.`
  return {
    create: `${CREATE_VIEW}${s}.${view} as select * from ${s}.${table} where "_deleted_at" is null`,
    comment: `comment on view ${s}.${view} is '${comment.replace(/'/g, "''")}'`,
  }
}

/**
 * `$tag$body$tag$` with a tag that does not occur in `body`, so a schema name
 * that happens to contain the delimiter cannot end the quote early.
 */
function dollarQuote(body: string, seed: string): string {
  let tag = seed
  while (body.includes(`$${tag}$`)) tag += '_'
  return `$${tag}$${body}$${tag}$`
}

/**
 * A stream's live view for a script applied without `applyViewStatement`
 * (`init --print-sql`): the ownership check that function makes, and then
 * the view's own DDL, in one `do` block.
 *
 * One block rather than a check followed by the plain statements, because
 * psql left to itself reports an error and carries on, so a separate check
 * that failed would stop nothing. Postgres would then let a bare `create or
 * replace view` overwrite a same-shaped view of somebody else's in place,
 * grants and all, and the comment that follows would claim it as ours.
 *
 * Stricter than `applyViewStatement` in one respect: an uncommented view
 * with exactly the generated definition, which `init` adopts, is refused
 * here too, since a script cannot compare definitions the way
 * `hasGeneratedDefinition` does. Dropping such a view is safe, and the
 * message says to. The message goes through `using message` so that a `%`
 * in the schema name is text rather than a format placeholder.
 */
export function guardedLiveViewSql(stream: TableDef, schema: string): string[] {
  if (stream.mode === 'append') return []
  const lit = (s: string) => `'${s.replace(/'/g, "''")}'`
  const view = liveViewName(stream)
  const qualified = lit(`${quoteIdent(schema)}.${quoteIdent(view)}`)
  const message = lit(
    `${schema}.${view} exists but was not generated by @workos/sync-postgres, so it was left alone. ` +
      'Rename or drop it, then apply the script again.',
  )
  const { create, comment } = liveViewStatements(stream, schema)
  const body = `
begin
  if to_regclass(${qualified}) is not null
     and not starts_with(coalesce(obj_description(to_regclass(${qualified}), 'pg_class'), ''), ${lit(GENERATED_BY)}) then
    raise exception using message = ${message};
  end if;
  execute ${dollarQuote(create, 'view')};
  execute ${dollarQuote(comment, 'comment')};
end
`
  return [`do ${dollarQuote(body, 'guard')};`]
}

/** True for the view statement `liveViewSql` emits. */
export function isViewStatement(sql: string): boolean {
  return sql.startsWith(CREATE_VIEW)
}

export interface ApplyViewOptions {
  /**
   * Rebuild a generated view that `create or replace view` refuses, carrying
   * its grants onto the new definition. Off by default; see
   * `PostgresDestinationOptions.repairViews` for what turning it on consents
   * to.
   */
  repairViews?: boolean
}

/**
 * Run a view statement, recovering from the one failure `create or replace
 * view` is designed to raise — but only with the operator's say-so.
 *
 * `create or replace` only accepts a definition that keeps every existing
 * column's name, type and position, appending new ones at the end. That holds
 * for the add-only DDL the engine issues, but not when the generated shape
 * itself changes between releases. The view then has to be dropped and
 * created fresh, and `drop view` discards its grants where `create or
 * replace` would have kept them. Re-granting a reader on the new definition
 * is an authorization decision, not a repair: the old view may have shown
 * fewer rows or different values, however much it looks like ours, and no
 * catalog check can prove two definitions equivalent. So the engine never
 * does it on its own. It fails, names the grants it would have to carry over,
 * and asks for `init --repair` (`repairViews`), which is the operator saying
 * those grantees may read the generated definition.
 *
 * Two kinds of view are refused even with `--repair`: one without the
 * generated comment, which is somebody else's; and one with the comment but
 * not the shape of `select *` over the table (`isSelectStarSnapshot`), which
 * was rebuilt by hand. The comment check also runs before `create or
 * replace`, because Postgres would otherwise overwrite a same-shaped view of
 * somebody else's in place, grants and all, without ever reaching the
 * fallback. The one uncommented view that is accepted is one defined exactly
 * as the engine would define it (`hasGeneratedDefinition`): that is what an
 * `init` that died between creating a view and commenting it would leave
 * behind, and finishing it is the right thing for the next run to do. The
 * create and its comment run in one transaction so that state cannot arise
 * from this code; the rule is there for whatever else produces it. A
 * generated view edited by hand but still same-shaped is overwritten in
 * place; the views are documented as not to be edited.
 *
 * The drop is not `cascade` — a user's view built on top of ours is theirs,
 * and taking it down silently would be worse than failing. During migration,
 * these inner transactions use savepoints so a failed create is rolled back
 * before the repair starts. The repair itself is atomic: a create that fails
 * after the drop — or a process that dies between the two — rolls back to the old
 * view instead of leaving readers with none.
 */
export async function applyViewStatement(
  db: SqlClient,
  sql: string,
  logger?: Logger,
  options: ApplyViewOptions = {},
): Promise<void> {
  const { view, table, body, create, comment } = parseViewStatement(sql)
  // A view that is not ours is refused before Postgres can overwrite it in
  // place. One with no comment at all may be ours, left half-made by a
  // process that died between the create and the comment; the definition
  // decides. One carrying another tool's comment is somebody else's claim,
  // whatever its definition says, and adopting it would silently replace
  // that claim with ours.
  const existing = await commentOn(db, view)
  if (existing === 'foreign') throw foreignView(view)
  if (existing === 'uncommented' && !(await hasGeneratedDefinition(db, view, body))) throw foreignView(view)
  let created = false
  try {
    await db.transaction(async (tx) => {
      await tx.exec(create)
      created = true
      await tx.exec(comment)
    })
    return
  } catch (err) {
    // Only a refused create has a fallback; a failed comment has rolled the
    // view back and is simply an error.
    if (created) throw err
    const reason = err instanceof Error ? err.message : String(err)
    await db.transaction(async (tx) => {
      const existing = await commentOn(tx, view)
      // Nothing there to repair: the create failed for some other reason.
      if (existing === 'missing') throw err
      if (existing !== 'commented') throw foreignView(view, reason)
      if (!(await isSelectStarSnapshot(tx, view, table))) {
        throw new Error(
          `${view} carries the @workos/sync-postgres comment but is not the generated definition of ` +
            `${table}, so it was left alone rather than widened to \`select *\` with its grants carried ` +
            `over (${reason}). Drop it, then apply the schema again.`,
        )
      }
      const grants = await grantsOn(tx, view)
      if (!options.repairViews) {
        const carried =
          grants.length === 0
            ? 'It holds no grants.'
            : `Re-creating it would carry these grants onto the generated definition:\n  ${grants.join('\n  ')}`
        throw new Error(
          `${view} cannot be replaced in place (${reason}). ${carried}\n` +
            `Run \`init --repair\` to drop and re-create it with those grants, or drop it by hand and ` +
            `re-grant selectively.`,
        )
      }
      logger?.warn('live view could not be replaced in place; dropping and re-creating it', { view, reason })
      await tx.exec(`drop view if exists ${view};`)
      await tx.exec(create)
      await tx.exec(comment)
      for (const grant of grants) {
        await tx.exec(grant)
        logger?.warn('re-applied a grant on the re-created live view', { view, grant })
      }
    })
  }
}

function foreignView(view: string, reason?: string): Error {
  return new Error(
    `${view} exists but was not generated by @workos/sync-postgres, so it was left alone` +
      `${reason ? ` (${reason})` : ''}. Rename or drop it, then apply the schema again.`,
  )
}

/**
 * Whether `view` is defined exactly as `body` would define it, comment or no
 * comment. Both sides are rendered by the server — `body` through a temporary
 * view that exists only inside this transaction — so the comparison is of
 * Postgres's own deparse, not of SQL text. Anything that differs, a narrower
 * `where` included, is not ours. A view created before a column was promoted
 * differs too, so an interrupted `init` followed by a catalog change is still
 * refused; the message says to drop it, which is safe for a view with no
 * comment and no data of its own.
 */
async function hasGeneratedDefinition(db: SqlClient, view: string, body: string): Promise<boolean> {
  const probe = '"_sync_postgres_view_probe"'
  return db.transaction(async (tx) => {
    await tx.exec(`create or replace temp view ${probe} as ${body};`)
    const r = await tx.query<{ same: boolean | null }>(
      `select pg_get_viewdef(to_regclass($1)) = pg_get_viewdef(to_regclass($2)) as same`,
      [view, `pg_temp.${probe}`],
    )
    await tx.exec(`drop view pg_temp.${probe};`)
    return r.rows[0]?.same === true
  })
}

/**
 * Whether anything is at `view` and, if so, what its comment says about who
 * owns it: the comment `liveViewSql` puts on every generated view
 * (`commented`), no comment at all (`uncommented`), or somebody else's
 * (`foreign`). `create or replace` keeps the comment, so ours survives every
 * in-place update since the view was first created. It is a claim, not a
 * proof; `isSelectStarSnapshot` is the check. The uncommented case is kept
 * apart from the foreign one because only it can be an interrupted creation
 * of ours; another tool's comment is that tool's claim and is never adopted.
 */
async function commentOn(db: SqlClient, view: string): Promise<'missing' | 'uncommented' | 'foreign' | 'commented'> {
  const r = await db.query<{ comment: string | null }>(
    `select obj_description(c.oid, 'pg_class') as comment from pg_class c where c.oid = to_regclass($1)`,
    [view],
  )
  const row = r.rows[0]
  if (!row) return 'missing'
  if (row.comment === null) return 'uncommented'
  return row.comment.startsWith(GENERATED_BY) ? 'commented' : 'foreign'
}

/**
 * Whether `view` is what `select *` over `table` produced at some point: it
 * reads that table and nothing else, and its columns are exactly the table's
 * first N, for some N. Postgres only ever appends columns, and refuses to
 * drop one a view depends on (short of `cascade`, which takes the view with
 * it), so a generated view that still exists can differ from its table only
 * by columns appended since — the columns a `select *` view is documented to
 * gain. Anything else — fewer columns, other columns, another table — was
 * rebuilt by hand, however it is commented, and may hide columns on purpose.
 * Column order is ignored: it changes nothing about what a grantee can read.
 *
 * Passing is necessary, not sufficient: a narrower `where`, or an expression
 * under a real column's name, passes too. That is why re-creating a view that
 * passes still needs `repairViews`.
 */
async function isSelectStarSnapshot(db: SqlClient, view: string, table: string): Promise<boolean> {
  const r = await db.query<{ ok: boolean | null }>(
    `with view_cols as (
       select attname from pg_attribute
        where attrelid = to_regclass($1) and attnum > 0 and not attisdropped),
     table_cols as (
       select attname, attnum from pg_attribute
        where attrelid = to_regclass($2) and attnum > 0 and not attisdropped),
     shared as (select t.attnum from view_cols v join table_cols t using (attname)),
     reads as (
       select distinct d.refobjid from pg_rewrite r
         join pg_depend d on d.classid = 'pg_rewrite'::regclass and d.objid = r.oid
        where r.ev_class = to_regclass($1)
          and d.refclassid = 'pg_class'::regclass and d.refobjid <> to_regclass($1)::oid)
     select (select count(*) from view_cols) = (select count(*) from shared)
        and (select count(*) from shared)
            = (select count(*) from table_cols where attnum <= (select max(attnum) from shared))
        and (select count(*) from reads) = 1
        and (select min(refobjid) from reads) = to_regclass($2)::oid as ok`,
    [view, table],
  )
  return r.rows[0]?.ok === true
}

/**
 * `grant` statements that re-create the privileges held on a view, so the
 * replacement is as readable as the original. Used twice: to tell the
 * operator which grants `init --repair` would carry over, and to carry them
 * over once it is given.
 *
 * `create or replace view` keeps a view's ACL; `drop view` discards it, and a
 * reader set up the way docs/queries.md suggests — `grant select on all tables
 * in schema` — would find the repaired view denying it. Default privileges do
 * not reliably cover this: they attach to objects created by the role that
 * ran `alter default privileges`, which need not be the role running `init`.
 *
 * Entries for the role running this are skipped: it owns the replacement,
 * which gives it everything implicitly. Any other role's are re-granted, the
 * previous owner's included. Column privileges are not carried over: the
 * fallback runs precisely because the column list changed, so they may name
 * columns that no longer exist.
 */
async function grantsOn(db: SqlClient, view: string): Promise<string[]> {
  const r = await db.query<{ grantee: string | null; privilege: string; grantable: boolean }>(
    `select r.rolname as grantee, a.privilege_type as privilege, a.is_grantable as grantable
       from pg_class c
       cross join lateral aclexplode(c.relacl) a
       left join pg_roles r on r.oid = a.grantee
      where c.oid = to_regclass($1) and r.rolname is distinct from current_user`,
    [view],
  )
  return r.rows.map(
    // A null role name is the pseudo-role `public`, which is a keyword, not an
    // identifier.
    ({ grantee, privilege, grantable }) =>
      `grant ${privilege} on ${view} to ${grantee === null ? 'public' : quoteIdent(grantee)}` +
      `${grantable ? ' with grant option' : ''};`,
  )
}

/**
 * Set the engine's own live view for `stream` aside while `fn` runs, then put
 * it back with the grants it had. For DDL that Postgres refuses while a view
 * depends on the column — `drop column` in a column repair, see `drift.ts` —
 * which would otherwise fail on every mirror table the moment it has a view.
 *
 * Only a view the engine generated is moved: the comment and the `select *`
 * proof both have to hold, exactly as in `applyViewStatement`. Anybody else's
 * view under the name, or one that was edited, stays where it is and the DDL
 * fails on it as it would have, so nothing is cascaded through a view we do
 * not own. The view that comes back is the catalog's current definition over
 * the same table, which shows its grantees the same rows and columns they saw
 * before (a rebuilt column moves to the end of the table, which `select *`
 * hides), so carrying the grants over widens nobody and needs no
 * `repairViews` consent. Column grants come back too, by column name: unlike
 * the fallback in `applyViewStatement`, a repair never changes the view's
 * column list, so every column a grant names is still there. Must run inside
 * the caller's transaction, so a failure part-way rolls the view back too.
 */
export async function withoutLiveView<T>(
  tx: SqlClient,
  stream: TableDef,
  schema: string,
  fn: () => Promise<T>,
): Promise<T> {
  const [sql] = liveViewSql(stream, schema)
  if (!sql) return fn()
  const { view, table, create, comment } = parseViewStatement(sql)
  if ((await commentOn(tx, view)) !== 'commented' || !(await isSelectStarSnapshot(tx, view, table))) {
    return fn()
  }
  const grants = [...(await grantsOn(tx, view)), ...(await columnGrantsOn(tx, view))]
  await tx.exec(`drop view ${view};`)
  const out = await fn()
  await tx.exec(create)
  await tx.exec(comment)
  for (const grant of grants) await tx.exec(grant)
  return out
}

/**
 * `grant` statements for the column-level privileges on a view, which live
 * in `pg_attribute.attacl` rather than the relation's ACL and so are invisible
 * to `grantsOn`. A reader given `select (id, email)` and nothing else would
 * otherwise be locked out by a repair that reports success.
 */
async function columnGrantsOn(db: SqlClient, view: string): Promise<string[]> {
  const r = await db.query<{ column: string; grantee: string | null; privilege: string; grantable: boolean }>(
    `select a.attname as column, r.rolname as grantee, x.privilege_type as privilege, x.is_grantable as grantable
       from pg_attribute a
       cross join lateral aclexplode(a.attacl) x
       left join pg_roles r on r.oid = x.grantee
      where a.attrelid = to_regclass($1) and a.attnum > 0 and not a.attisdropped and a.attacl is not null
        and r.rolname is distinct from current_user
      order by a.attnum`,
    [view],
  )
  return r.rows.map(
    ({ column, grantee, privilege, grantable }) =>
      `grant ${privilege} (${quoteIdent(column)}) on ${view} to ${grantee === null ? 'public' : quoteIdent(grantee)}` +
      `${grantable ? ' with grant option' : ''};`,
  )
}

/**
 * The parts of a statement from `liveViewSql`: the `create or replace view`
 * and the `comment on view` it carries, the `"schema"."view"` and
 * `"schema"."table"` they name, and the view's `select` body. Every
 * identifier is always quoted there and the comment never spans a line,
 * which is what makes this parse safe.
 */
function parseViewStatement(sql: string): {
  view: string
  table: string
  body: string
  create: string
  comment: string
} {
  const ident = '"(?:[^"]|"")+"\\."(?:[^"]|"")+"'
  const m = new RegExp(
    `^(create or replace view (${ident}) as (select \\* from (${ident}) where "_deleted_at" is null);)\\n(comment on view .+;)$`,
  ).exec(sql)
  if (!m) throw new Error(`not a view statement: ${sql.slice(0, 80)}`)
  return { create: m[1]!, view: m[2]!, body: m[3]!, table: m[4]!, comment: m[5]! }
}
