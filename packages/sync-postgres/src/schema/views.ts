/**
 * Live views.
 *
 * Every query against a mirror table has to remember `where "_deleted_at" is
 * null`, and forgetting it is the most common query mistake: a seat count that
 * includes users who left, a join that resurrects a revoked membership.
 * Fivetran and dbt users solve this with a view over each soft-deleted table.
 * Ours are generated from the catalog, in the same pass as the tables, so they
 * can never drift from them.
 *
 * Only the view layer is new. The engine keeps writing, redacting, reconciling
 * and reporting freshness against the base tables, and the base tables remain
 * the place to tell "deleted" from "never seen" (docs/consistency.md).
 */
import type { Logger, StreamDef } from '@workos/sync-engine'
import type { SqlClient } from '../db/client.js'
import { quoteIdent, safeIdentifier } from './identifiers.js'

export const LIVE_VIEW_SUFFIX = '_live'

/**
 * How every generated view's comment begins, and so how the engine tells its
 * own views from one somebody else created under the same name.
 */
export const GENERATED_BY = 'Generated by @workos/sync-postgres'

/**
 * `<stream>_live`, truncated the same way table names are, so a long stream
 * name cannot produce a view name that Postgres silently cuts to something
 * else.
 */
export function liveViewName(stream: StreamDef): string {
  return safeIdentifier(`${stream.name}${LIVE_VIEW_SUFFIX}`)
}

const CREATE_VIEW = 'create or replace view '

/**
 * DDL for one stream's live view. Empty for append-only streams: they have no
 * `_deleted_at` column, so there is nothing to filter and a view would only
 * suggest there was.
 *
 * `select *` is deliberate: the view must expose every column the table has,
 * including ones promoted later through `extraColumns`. Postgres expands `*`
 * when the view is created, not when it is queried, which is why
 * `buildSchemaSql` emits these after `addColumnsSql` — re-creating the view
 * is how it picks up a new column.
 */
export function liveViewSql(stream: StreamDef, schema: string): string[] {
  if (stream.mode === 'append') return []
  const s = quoteIdent(schema)
  const table = quoteIdent(safeIdentifier(stream.name))
  const view = quoteIdent(liveViewName(stream))
  const comment =
    `${GENERATED_BY}: ${schema}.${stream.name} without tombstoned rows ` +
    `("_deleted_at" is null). Do not edit; it is re-created every time the schema is applied.`
  return [
    `${CREATE_VIEW}${s}.${view} as select * from ${s}.${table} where "_deleted_at" is null;`,
    `comment on view ${s}.${view} is '${comment.replace(/'/g, "''")}';`,
  ]
}

/** True for the `create or replace view` statement `liveViewSql` emits. */
export function isViewStatement(sql: string): boolean {
  return sql.startsWith(CREATE_VIEW)
}

/**
 * Run a view statement, recovering from the one failure `create or replace
 * view` is designed to raise.
 *
 * `create or replace` only accepts a definition that keeps every existing
 * column's name, type and position, appending new ones at the end. That holds
 * for the add-only DDL the engine issues, but not when the generated shape
 * itself changes between releases. Then a view of our own is dropped and
 * created fresh: it holds no data, so nothing is lost, and the generated
 * definition is the only one it should ever have. The drop is not `cascade` —
 * a user's view built on top of ours is theirs, and taking it down silently
 * would be worse than failing.
 *
 * A view under our name that is not demonstrably one of ours is not repaired
 * at all. It may be narrower than `select *` on purpose, with grants given
 * with that in mind, so neither replacing it nor carrying its grants onto a
 * wider definition is ours to decide: `init` fails and says what to do. The
 * comment a generated view carries is the claim; `isSelectStarSnapshot` is
 * the proof, and both are required.
 *
 * This relies on `migrate` running each statement outside a transaction;
 * inside one, the failed create would already have aborted it. The repair
 * itself is one transaction: DDL is transactional in Postgres, so a create
 * that fails after the drop — or a process that dies between the two — rolls
 * back to the old view instead of leaving readers with none.
 */
export async function applyViewStatement(db: SqlClient, sql: string, logger?: Logger): Promise<void> {
  try {
    await db.exec(sql)
  } catch (err) {
    const { view, table } = parseViewStatement(sql)
    const reason = err instanceof Error ? err.message : String(err)
    await db.transaction(async (tx) => {
      const existing = await describeView(tx, view, table)
      // Nothing there to repair: the create failed for some other reason.
      if (existing === 'missing') throw err
      if (existing === 'foreign') {
        throw new Error(
          `${view} exists but was not generated by @workos/sync-postgres, so it was left alone ` +
            `(${reason}). Rename or drop it, then apply the schema again.`,
        )
      }
      if (existing === 'altered') {
        throw new Error(
          `${view} carries the @workos/sync-postgres comment but is not the generated definition of ` +
            `${table}, so it was left alone rather than widened to \`select *\` with its grants carried ` +
            `over (${reason}). Drop it, then apply the schema again.`,
        )
      }
      logger?.warn('live view could not be replaced in place; dropping and re-creating it', { view, reason })
      const grants = await grantsOn(tx, view)
      await tx.exec(`drop view if exists ${view};`)
      await tx.exec(sql)
      for (const grant of grants) await tx.exec(grant)
    })
  }
}

/**
 * What is at `view`: nothing, a relation without the generated comment, one
 * with the comment but not the generated shape, or a generated view. The
 * comment is what `liveViewSql` puts on every view it creates, and `create or
 * replace` keeps it, so it survives every in-place update since.
 */
async function describeView(
  db: SqlClient,
  view: string,
  table: string,
): Promise<'missing' | 'foreign' | 'altered' | 'generated'> {
  const r = await db.query<{ comment: string | null }>(
    `select obj_description(c.oid, 'pg_class') as comment from pg_class c where c.oid = to_regclass($1)`,
    [view],
  )
  const row = r.rows[0]
  if (!row) return 'missing'
  if (!(row.comment ?? '').startsWith(GENERATED_BY)) return 'foreign'
  return (await isSelectStarSnapshot(db, view, table)) ? 'generated' : 'altered'
}

/**
 * Whether `view` is what `select *` over `table` produced at some point: it
 * reads that table and nothing else, and its columns are exactly the table's
 * first N, for some N. Postgres only ever appends columns, and refuses to
 * drop one a view depends on (short of `cascade`, which takes the view with
 * it), so a generated view that still exists can differ from its table only
 * by columns appended since — the columns a `select *` view is documented to
 * gain. Anything else — fewer columns, other columns, another table — was
 * edited by hand, however it is commented, and may hide columns on purpose.
 * Column order is ignored: it changes nothing about what a grantee can read.
 */
async function isSelectStarSnapshot(db: SqlClient, view: string, table: string): Promise<boolean> {
  const r = await db.query<{ ok: boolean | null }>(
    `with view_cols as (
       select attname from pg_attribute
        where attrelid = to_regclass($1) and attnum > 0 and not attisdropped),
     table_cols as (
       select attname, attnum from pg_attribute
        where attrelid = to_regclass($2) and attnum > 0 and not attisdropped),
     shared as (select t.attnum from view_cols v join table_cols t using (attname)),
     reads as (
       select distinct d.refobjid from pg_rewrite r
         join pg_depend d on d.classid = 'pg_rewrite'::regclass and d.objid = r.oid
        where r.ev_class = to_regclass($1)
          and d.refclassid = 'pg_class'::regclass and d.refobjid <> to_regclass($1)::oid)
     select (select count(*) from view_cols) = (select count(*) from shared)
        and (select count(*) from shared)
            = (select count(*) from table_cols where attnum <= (select max(attnum) from shared))
        and (select count(*) from reads) = 1
        and (select min(refobjid) from reads) = to_regclass($2)::oid as ok`,
    [view, table],
  )
  return r.rows[0]?.ok === true
}

/**
 * `grant` statements that re-create the privileges held on a view, so the
 * replacement is as readable as the original. Only reached once
 * `isSelectStarSnapshot` has shown the old view to be `select *` over the
 * same table: the replacement can then expose at most the columns promoted
 * since, which every grantee of a `select *` view is documented to see, so
 * carrying the grants over widens nobody's access beyond that.
 *
 * `create or replace view` keeps a view's ACL; `drop view` discards it, and a
 * reader set up the way docs/queries.md suggests — `grant select on all tables
 * in schema` — would find the repaired view denying it. Default privileges do
 * not reliably cover this: they attach to objects created by the role that
 * ran `alter default privileges`, which need not be the role running `init`.
 *
 * Entries for the role running this are skipped: it owns the replacement,
 * which gives it everything implicitly. Any other role's are re-granted, the
 * previous owner's included. Column privileges are not carried over: the
 * fallback runs precisely because the column list changed, so they may name
 * columns that no longer exist.
 */
async function grantsOn(db: SqlClient, view: string): Promise<string[]> {
  const r = await db.query<{ grantee: string | null; privilege: string; grantable: boolean }>(
    `select r.rolname as grantee, a.privilege_type as privilege, a.is_grantable as grantable
       from pg_class c
       cross join lateral aclexplode(c.relacl) a
       left join pg_roles r on r.oid = a.grantee
      where c.oid = to_regclass($1) and r.rolname is distinct from current_user`,
    [view],
  )
  return r.rows.map(
    // A null role name is the pseudo-role `public`, which is a keyword, not an
    // identifier.
    ({ grantee, privilege, grantable }) =>
      `grant ${privilege} on ${view} to ${grantee === null ? 'public' : quoteIdent(grantee)}` +
      `${grantable ? ' with grant option' : ''};`,
  )
}

/**
 * The `"schema"."view"` and `"schema"."table"` a statement from `liveViewSql`
 * names. Every part is always quoted there, which is what makes this parse
 * safe.
 */
function parseViewStatement(sql: string): { view: string; table: string } {
  const ident = '"(?:[^"]|"")+"\\."(?:[^"]|"")+"'
  const m = new RegExp(`^create or replace view (${ident}) as select \\* from (${ident}) where `).exec(sql)
  if (!m) throw new Error(`not a view statement: ${sql.slice(0, 80)}`)
  return { view: m[1]!, table: m[2]! }
}
