#!/usr/bin/env node
/**
 * workos-sync-postgres — the command line.
 *
 * The commands, their flags, their exit codes and the way the environment
 * is read are the engine's (`runCli`); this file says what Postgres does
 * differently: how its destination is built, what `init` reports, the DDL
 * `init --print-sql` prints, and the words the help text needs.
 */
import {
  runCli,
  exitWith,
  invokedDirectly,
  selectStreams,
  type CliFlags,
  type CliSpec,
  type MainDeps,
} from '@workos/sync-engine'
import { PostgresDestination } from './destination.js'
import { buildSchemaSql } from './schema/ddl.js'
import { fingerprint } from './schema/migrate.js'
import type { SqlClient } from './db/client.js'

function schemaFromFlags(flags: CliFlags): string {
  return (flags['schema'] as string) ?? process.env['WORKOS_SYNC_SCHEMA'] ?? 'workos'
}

/**
 * `init --print-sql`: the DDL `init` would run, as one script for psql or a
 * migration file, instead of running it. Nothing is touched, so no database
 * or API key is needed; the stream selection is the engine's own.
 *
 * The header names the catalog fingerprint but the script deliberately does
 * not record it. A recorded fingerprint means "the live columns were checked
 * against this catalog" (see `migrate`), and only `init` can check. So after
 * the script is applied, `init` still has to run once: it finds the DDL in
 * place, runs that check, and records the fingerprint, after which later
 * runs are no-ops.
 *
 * The one check the script does carry is the ownership of `_live` views, as
 * SQL (`guardedLiveViewSql`): applied by hand, nothing else would stop it
 * from overwriting a view somebody else created under that name. The schema
 * name is JSON-quoted in the header so that a line break in it cannot end
 * the comment early; the DDL itself quotes it as an identifier.
 */
export function printSchemaSql(streamNames: string[] | undefined, schema: string): string {
  const streams = selectStreams(streamNames)
  const header = [
    '-- Generated by workos-sync-postgres init --print-sql.',
    `-- Schema ${JSON.stringify(schema)}, catalog fingerprint ${fingerprint(streams, schema)}.`,
    '-- Apply this, then run `init` once: it records the fingerprint after checking',
    '-- the live columns against the catalog, which this script cannot do. Like',
    '-- `init`, the script refuses to replace a _live view it did not generate.',
  ].join('\n')
  return `${header}\n\n${buildSchemaSql(streams, schema, { guardViews: true }).join('\n\n')}\n`
}

export const spec: CliSpec<SqlClient, PostgresDestination> = {
  command: 'workos-sync-postgres',
  technology: 'Postgres',
  rowNoun: 'row',
  connection: 'Postgres connection string',
  tlsCaVar: 'WORKOS_SYNC_PG_SSL_CA',
  serviceName: 'workos-sync-postgres',
  init: {
    name: 'init [--repair] [--print-sql]',
    text: [
      'Create the schema and bookkeeping tables. Exits 2 if a generated',
      'column has drifted from the catalog, and fails if a generated _live',
      'view must be rebuilt; --repair rebuilds columns from _raw and views',
      'with their grants carried over. --print-sql prints the DDL instead',
      'of running it, with no database needed; apply it, then run init',
      'once so it records the fingerprint',
    ],
  },
  targetFlags: [{ name: '--schema <name>', text: ['Target schema (or WORKOS_SYNC_SCHEMA; default: workos)'] }],
  targetEnv: [{ name: 'WORKOS_SYNC_SCHEMA', text: ['Target schema (default: workos)'] }],
  printSchemaSql: (streamNames, flags) => printSchemaSql(streamNames, schemaFromFlags(flags)),
  // Built apart from the rest of the config because `init` reads the drift
  // report back off it after the engine has run; the engine's own `init()`
  // returns nothing.
  destination: (flags, { databaseUrl, sslCa, db, syncId, repair }) =>
    new PostgresDestination({
      databaseUrl,
      sslCa,
      db,
      schema: schemaFromFlags(flags),
      syncId,
      repairColumns: repair,
      repairViews: repair,
    }),
  initReport: (destination) => {
    const drift = destination.lastMigration?.drift ?? []
    const repaired = destination.lastMigration?.repaired ?? []
    return {
      output: drift.length > 0 || repaired.length > 0 ? { repaired, drift } : undefined,
      // Orphans are advisory. Anything else means a projection is wrong and
      // the fingerprint was withheld.
      failed: drift.some((d) => d.kind !== 'orphan'),
    }
  },
}

export type { MainDeps }

export function main(argv = process.argv.slice(2), deps: MainDeps<SqlClient> = {}): Promise<number> {
  return runCli(spec, argv, deps)
}

if (invokedDirectly(process.argv[1], import.meta.url)) exitWith(main())
