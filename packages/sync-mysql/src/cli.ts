#!/usr/bin/env node
/**
 * workos-sync-mysql — the command line.
 *
 * The commands, their flags, their exit codes and the way the environment
 * is read are the engine's (`runCli`); this file says what MySQL does
 * differently: how its destination is built, what `init` reports, the DDL
 * `init --print-sql` prints, and the words the help text needs.
 */
import {
  runCli,
  exitWith,
  invokedDirectly,
  selectStreams,
  type CliFlags,
  type CliSpec,
  type MainDeps,
} from '@workos/sync-engine'
import { MysqlDestination } from './destination.js'
import { buildSchemaSql, parseTablePrefix } from './schema/ddl.js'
import { fingerprint } from './schema/migrate.js'
import type { SqlClient } from './db/client.js'

function schemaFromFlags(flags: CliFlags): string {
  return (flags['schema'] as string) ?? process.env['WORKOS_SYNC_SCHEMA'] ?? 'workos'
}

/**
 * `--table-prefix`, or `WORKOS_SYNC_TABLE_PREFIX` when the flag is absent.
 * Unchecked: the destination checks it, and `printSchemaSql` does. A flag
 * with no value is refused here rather than read as "no prefix". It is what
 * `--table-prefix "$UNSET"` leaves behind, and running on without one would
 * write to the unprefixed tables the flag was given to keep clear of.
 */
function tablePrefixFromFlags(flags: CliFlags): string | undefined {
  const flag = flags['table-prefix']
  if (flag === undefined) return process.env['WORKOS_SYNC_TABLE_PREFIX']
  if (typeof flag !== 'string') {
    throw new Error('invalid --table-prefix: expected a prefix of lowercase letters, digits and underscores')
  }
  return flag
}

/**
 * `init --print-sql`: the DDL `init` would run on a fresh database, as one
 * script for the mysql client or a migration file, instead of running it.
 * Nothing is touched, so no database or API key is needed; the stream
 * selection is the engine's own.
 *
 * The header names the catalog fingerprint but the script deliberately does
 * not record it. A recorded fingerprint means "the live columns were checked
 * against this catalog" (see `migrate`), and only `init` can check. So after
 * the script is applied, `init` still has to run once: it finds the DDL in
 * place, runs that check, and records the fingerprint, after which later
 * runs are no-ops. Columns added to a table that already exists are the
 * one thing the script cannot express — MySQL has no `ADD COLUMN IF NOT
 * EXISTS` — and `init` adds them. The schema name is JSON-quoted in the
 * header so that a line break in it cannot end the comment early; the DDL
 * itself quotes it as an identifier.
 *
 * A table prefix is part of every name printed and of the fingerprint, so
 * the script has to be printed with the prefix `init` will then run with;
 * the header names it for that reason.
 */
export function printSchemaSql(streamNames: string[] | undefined, schema: string, tablePrefix?: string): string {
  const streams = selectStreams(streamNames)
  const ref = { schema, prefix: parseTablePrefix(tablePrefix) }
  const prefixed = ref.prefix ? `, table prefix ${JSON.stringify(ref.prefix)}` : ''
  const header = [
    '-- Generated by workos-sync-mysql init --print-sql.',
    `-- Schema ${JSON.stringify(schema)}${prefixed}, catalog fingerprint ${fingerprint(streams, ref)}.`,
    '-- Apply this to a fresh database, then run `init` once: it records the',
    '-- fingerprint after checking the live columns against the catalog, which',
    '-- this script cannot do.',
  ].join('\n')
  return `${header}\n\n${buildSchemaSql(streams, ref)
    .map((s) => `${s};`)
    .join('\n\n')}\n`
}

export const spec: CliSpec<SqlClient, MysqlDestination> = {
  command: 'workos-sync-mysql',
  technology: 'MySQL',
  rowNoun: 'row',
  connection: 'MySQL connection string',
  tlsCaVar: 'WORKOS_SYNC_MYSQL_SSL_CA',
  // mysql2 connects in plaintext unless it is told otherwise.
  tlsCaDefault: 'no TLS, unless the connection string has an ssl parameter',
  serviceName: 'workos-sync-mysql',
  init: {
    name: 'init [--repair] [--print-sql]',
    text: [
      'Create the database and bookkeeping tables. Exits 2 if a generated',
      'column has drifted from the catalog, and fails if a view under a',
      'generated _live name is not the generated shape; --repair rebuilds',
      'columns from _raw and replaces such views. --print-sql prints the',
      'DDL for a fresh database instead of running it, with no database',
      'needed; apply it, then run init once so it records the fingerprint',
    ],
  },
  targetFlags: [
    { name: '--schema <name>', text: ['Target database (or WORKOS_SYNC_SCHEMA; default: workos)'] },
    {
      name: '--table-prefix <prefix>',
      text: [
        'Prefix on every table and view the mirror creates, for a',
        'database it shares with your own tables: users becomes',
        '<prefix>users (or WORKOS_SYNC_TABLE_PREFIX; default: none)',
      ],
    },
  ],
  targetEnv: [
    { name: 'WORKOS_SYNC_SCHEMA', text: ['Target database (default: workos)'] },
    {
      name: 'WORKOS_SYNC_TABLE_PREFIX',
      text: ['Prefix on every table and view the mirror creates (default: none)'],
    },
  ],
  printSchemaSql: (streamNames, flags) =>
    printSchemaSql(streamNames, schemaFromFlags(flags), tablePrefixFromFlags(flags)),
  // Built apart from the rest of the config because `init` reads the drift
  // report back off it after the engine has run; the engine's own `init()`
  // returns nothing.
  destination: (flags, { databaseUrl, sslCa, db, syncId, repair }) =>
    new MysqlDestination({
      databaseUrl,
      sslCa,
      db,
      schema: schemaFromFlags(flags),
      tablePrefix: tablePrefixFromFlags(flags),
      syncId,
      repairColumns: repair,
      repairViews: repair,
    }),
  initReport: (destination) => {
    const drift = destination.lastMigration?.drift ?? []
    const repaired = destination.lastMigration?.repaired ?? []
    return {
      output: drift.length > 0 || repaired.length > 0 ? { repaired, drift } : undefined,
      // Orphans are advisory. Anything else means a projection is wrong and
      // the fingerprint was withheld.
      failed: drift.some((d) => d.kind !== 'orphan'),
    }
  },
}

export type { MainDeps }

export function main(argv = process.argv.slice(2), deps: MainDeps<SqlClient> = {}): Promise<number> {
  return runCli(spec, argv, deps)
}

if (invokedDirectly(process.argv[1], import.meta.url)) exitWith(main())
